"""DATASET_OBS2.md (docs/worldmodel/wm5/GOAL.md 6.2.6) from the committed record files (`runs/record/`) and
`runs/describe/describe.json` (train worlds and val families only). The test effect distribution is added from
`runs/obs2_base/obs2_base.json` only when it exists (after METRICS part b). numpy only.

usage: python3 tools/worldmodel/wm5/dataset_doc.py [--out docs/worldmodel/wm5/DATASET_OBS2.md]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
RUNS = REPO / "docs/worldmodel/wm5/runs"
ARMS = ("gf240", "sp240", "rw120")
OUTCOMES = ("food_stock", "alive", "deaths", "settlements_alive")


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def pct(x: float) -> str:
    return f"{100 * x:.1f} %"


def dist_table(dist: dict) -> list[str]:
    L = ["| arm | outcome | 7 d: mean (std), median, share ≠ 0 | 30 d: mean (std), median, share ≠ 0 |", "|---|---|---|---|"]
    for a in ARMS:
        if a not in dist:
            continue
        for o in OUTCOMES:
            cells = []
            for lag in ("7d", "30d"):
                q = dist[a].get(f"{o}|{lag}")
                cells.append("—" if q is None else f"{q['mean']:+.2f} ({q['std']:.2f}), {q['median']:+.1f}, {q['share_nonzero']:.2f}")
            L.append(f"| {a} | {o} | {cells[0]} | {cells[1]} |")
    return L


def render() -> str:
    fin = load(RUNS / "record" / "finalize.json")
    s = fin["summary"]
    L = ["# Dataset obs2 (WM-5): the sequential multi-cast observational split of `game_v19`", "",
         "Generated by `tools/worldmodel/wm5/dataset_doc.py` from `runs/record/` (the recording's own checks) and "
         "`runs/describe/describe.json` (train worlds and val families only). Recorded on the DGX by the frozen WM-2 "
         "recorder (`_build/src_wm2`, `WORLDSIM_GIT_SHA` `f5373ab2…`); data root `/home/hyunlord/work/worldsim-wm-data/obs2/`; "
         "manifest `obs2_manifest.json`. Policy, roles, rounds and reference rows: METRICS.md part a; code `tools/worldmodel/wm5/"
         "policy2.py`, `obs2.py`.", "", "## Rounds", "",
         "| round | worlds read | new acts | gift / spoil / rot | recorded | prefix check | differ after the act | recording seconds |",
         "|---|---|---|---|---|---|---|---|"]
    r0 = load(RUNS / "record" / "r0_verify.json")
    L.append(f"| 0 (factual) | — | — | — | {r0['episodes']} | verified, rows {r0['rows']} | — | "
             f"{int((RUNS / 'record' / 'r0.end').read_text()) - int((RUNS / 'record' / 'r0.start').read_text())} |")
    k = 1
    while (RUNS / "record" / f"round{k}_schedules.json").exists():
        sc = load(RUNS / "record" / f"round{k}_schedules.json")
        ck = load(RUNS / "record" / f"round{k}_check.json")
        secs = int((RUNS / "record" / f"round{k}_record.end").read_text()) - int((RUNS / "record" / f"round{k}_record.start").read_text())
        ac = sc["arm_counts"]
        L.append(f"| {k} | {sc['read']} | {sc['new_casts']} | {ac['gf240']} / {ac['sp240']} / {ac['rw120']} | {ck['worlds']} | "
                 f"{'all OK' if ck['all_ok'] else 'FAIL ' + str(ck['bad'][:5])} | {ck['after_differs']} | {secs} |")
        k += 1
    L += ["", f"`finalize`: the policy replayed on every world's observed (last-round) episode reproduces every round's acts and "
          f"row probabilities for {fin['worlds'] - len(fin['bad'])} / {fin['worlds']} worlds (`replay_ok`). Rows: "
          + ", ".join(f"{n} {v:,}" for n, v in s["status_counts"].items()) + ".", "",
          "## Acts per world and roles", "",
          "| role | worlds | never acted | acts | acts per world | worlds with 0 / 1 / 2 / 3 / 4 / 5 acts | gift / spoil / rot share | acts with an earlier act in the history |",
          "|---|---|---|---|---|---|---|---|"]
    for role in ("all", "train", "val", "test"):
        b = s[role]
        h = b["casts_per_world_hist"]
        L.append(f"| {role} | {b['worlds']} | {b['never']} ({pct(b['never_share'])}) | {b['casts']} | {b['casts_per_world_mean']:.2f} | "
                 + " / ".join(str(h[str(i)]) for i in range(6)) + " | "
                 + " / ".join(pct(b["arm_shares"][a]) for a in ARMS) + f" | {b['casts_with_earlier_cast']} ({pct(b['share_with_earlier_cast'])}) |")
    L += ["", "## The confounding: act shares per food-per-person tercile (decision rows of every world)", "",
          "| tercile of f at the decision row | decision rows | acts | daily act rate | gift | spoil | rot |", "|---|---|---|---|---|---|---|"]
    names = {"0": "low (f < 8.08)", "1": "middle", "2": "high (f ≥ 12.1)"}
    for t, b in s["by_f_tercile"].items():
        L.append(f"| {names[t]} | {b['decision_rows']:,} | {b['casts']} | {b['cast_rate']:.4f} | "
                 + " | ".join(f"{pct(b['arm_shares'][a])} ({b['arm_counts'][a]})" for a in ARMS) + " |")
    L += ["", "Gifts go to hungry worlds and spoils to fed ones, with WM-4's ratios (15 : 1 at the extremes); every act has "
          "positive probability on every decision row (overlap)."]
    fs = load(RUNS / "record" / "fam_schedules.json")
    fc = load(RUNS / "record" / "fam_check.json")
    if fs:
        L += ["", "## Families (val and test worlds, two reference rows each)", "",
              f"Family schedules: {fs['families']['val']} val and {fs['families']['test']} test families "
              f"(c1, c2 per world); a non-empty `pre` at c1 in {fs['pre_nonempty']['c1']} and at c2 in {fs['pre_nonempty']['c2']} "
              "families (an empty `pre` is the recorder's `none` member, DECISIONS L1.2). Val families: replicate 0; test "
              "families: replicates 0 and 1."]
    if fc:
        L.append(f"`fam-check`: {fc['families'] - len(fc['bad'])} / {fc['expected']} families pass (every member equals the observed "
                 f"episode on rows < c, carries exactly `pre` (+ the act at c), fork at c with the role's replicates); "
                 f"`none_r0` = round-0 factual checked in {fc['none_r0_equal_r0_checked']} families; "
                 f"`pre_r0` = a fresh unforked recording in {fc['unforked_checked']} sampled test families. The independent "
                 "review (REVIEW.md round 1, m5) also found every non-empty `pre_r0` (419) identical to the world's round-1 "
                 "episode, rows ≤ c (the fork row included) identical in 24 test families, and their 1,152 truths equal to "
                 "`obs2_base.json`. Applied amounts: some acts apply less than requested (a spoil or rot limited by the store; "
                 "`applied` 0 when the store is empty), as in WM-4; the recorded `applied` is in every member's interventions.")
    d = load(RUNS / "describe" / "describe.json")
    if d:
        L += ["", "## Effective sample sizes of the multi-cast IPW (observed train worlds, GOAL.md 7.2)", "",
              "| arm | lag | treated units | with an earlier act | ESS treated | controls | ESS controls | max weight treated / controls |",
              "|---|---|---|---|---|---|---|---|"]
        for a in ARMS:
            for lag in ("7d", "30d"):
                c = d["pooled"][a][lag]
                L.append(f"| {a} | {lag} | {c['treated']} | {c['treated_with_earlier_cast']} | {c['ess_treated']:.1f} | {c['controls']:,} | "
                         f"{c['ess_controls']:.1f} | {c['max_weight_treated']:.1f} / {c['max_weight_controls']:.2f} |")
        L += ["", f"## True effects on the val families ({d['val_cases']} cases, replicate 0; c1 and c2 pooled)", ""]
        L += dist_table(d["distribution_val"]["all"])
    b = load(RUNS / "obs2_base" / "obs2_base.json")
    if b:
        L += ["", "## True effects on the test families (replicate 0; added after METRICS part b)", ""]
        L += dist_table(b["distribution"]["test"])
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(REPO / "docs/worldmodel/wm5/DATASET_OBS2.md"))
    a = ap.parse_args(argv)
    Path(a.out).write_text(render())
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
