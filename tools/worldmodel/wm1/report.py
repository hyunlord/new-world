"""Build docs/worldmodel/wm1/RESULTS.md (the W table and every result table) from the fetched run files.

usage: python3 tools/worldmodel/wm1/report.py   (reads docs/worldmodel/wm1/runs/*/; numpy only, no data access)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np

import wm1  # noqa: F401
import bench_v0 as b
from wm1.common import REPO, fmt

DOCS = REPO / "docs/worldmodel/wm1"
RUNS = DOCS / "runs"
BASE_RUN = "w1_repro_832eaa2c"
RECIPES = {"r1": "", "r2": "_r2", "r3": "_r3"}


def runs_for(suffix: str) -> tuple[tuple[str, ...], dict[str, str]]:
    main = tuple(f"m1gru_main{suffix}_s{i}" for i in range(3))
    return main, {"sev-blind, action-aware (main)": main[0], "sev-on, action-aware": f"m1gru_sevon_aa{suffix}_s0",
                  "sev-blind, action-blind": f"m1gru_blind_ab{suffix}_s0", "sev-on, action-blind": f"m1gru_sevon_ab{suffix}_s0"}


def val_168(run: str) -> float:
    v = load(run, "val_metrics.json")
    return float(np.mean([v["val"]["T2"]["168"][n]["mean"] for n in v["val"]["T2"]["168"]])) if v else float("inf")


def val_t1(run: str) -> float:
    v = load(run, "val_metrics.json")
    return float(np.mean([v["val"]["T1"][n]["mean"] for n in v["val"]["T1"]])) if v else float("inf")


def choose_recipe() -> str:
    """The main recipe: the lowest validation T2 168 h of the main seed-0 run (A val and B val mean), T1 breaking ties."""
    scores = {r: (round(val_168(f"m1gru_main{sfx}_s0"), 6), val_t1(f"m1gru_main{sfx}_s0")) for r, sfx in RECIPES.items()}
    return min(scores, key=scores.get)


MAIN_SEEDS, VARIANT_RUNS = runs_for("")
TESTS = ("A_test", "B_test", "OOD_v12", "OOD_long")
W2_SPLITS = ("A_test", "B_test", "OOD_long")
RANKED = ("dark_nights", "cold_member_hours", "food_store")


def load(run: str, name: str):
    p = RUNS / run / name
    return json.loads(p.read_text()) if p.exists() else None


def ridge_variants() -> dict | None:
    runs = sorted(p.name for p in RUNS.iterdir() if p.name.startswith("ridge_variants_"))
    return load(runs[-1], "ridge_variants.json") if runs else None


def best_baseline(scores: dict) -> tuple[float, str]:
    return min((v["mean"], k) for k, v in scores.items())


def seeds(runs, getter):
    vals = [getter(load(r, "metrics.json")) for r in runs if load(r, "metrics.json")]
    return np.array(vals, dtype=float)


def mean_range(v: np.ndarray, digits: int = 3) -> str:
    if len(v) == 0:
        return "—"
    if len(v) == 1:
        return fmt(float(v[0]), digits)
    return f"{v.mean():.{digits}f} [{v.min():.{digits}f}, {v.max():.{digits}f}]"


def t4_best_baseline(base: dict, variant: str, target: str) -> tuple[float, str]:
    opts = [(base["T4"][n][variant][target]["nmae"], n) for n in ("zero_effect", "val_mean_effect")]
    opts = [o for o in opts if o[0] is not None]
    return min(opts) if opts else (None, "—")


def main() -> int:
    global MAIN_SEEDS, VARIANT_RUNS
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    recipe = args[0] if args else choose_recipe()
    MAIN_SEEDS, VARIANT_RUNS = runs_for(RECIPES[recipe])
    base = load(BASE_RUN, "baselines.json")
    w1 = load(BASE_RUN, "w1_repro.json")
    bench = json.loads((REPO / "docs/worldmodel/bench_v0.json").read_text())
    main_runs = [r for r in MAIN_SEEDS if load(r, "metrics.json")]
    m0 = load(MAIN_SEEDS[0], "metrics.json")
    L = ["# WM-1 results", "", "Generated by `tools/worldmodel/wm1/report.py` from `docs/worldmodel/wm1/runs/*/` (test metrics "
         "`metrics.json`, validation `val_metrics.json`, baselines `" + BASE_RUN + "/baselines.json`). nMAE = MAE / the bench's "
         "split std; mean over the 8 variables V unless stated. Three-seed values are mean [min, max].", "",
         f"Main recipe: **{recipe}** (chosen by validation T2 168 h of the main seed-0 run: "
         + ", ".join(f"{r} {val_168(f'm1gru_main{sfx}_s0'):.3f}" for r, sfx in RECIPES.items()) + ").", ""]
    # ---------------------------------------------------------------- W table
    W = []
    W.append(("W1", "harness fidelity (bench baselines to 1e-3, T1–T4, every split)", "—", f"max |diff| {w1['max_abs_diff']:.1e}",
              "PASS" if w1["pass"] else "FAIL"))
    rv = ridge_variants()
    if m0:
        t1_ok, t1_rows = True, []
        for s_ in TESTS:
            cand = {k: float(np.nanmean(v)) for k, v in bench["T1"][s_].items()}
            if rv:
                cand.update({k: v["mean"] for k, v in rv["T1"][s_].items()})
            ref = min(cand.values())
            v = seeds(main_runs, lambda m: m["T1"][s_]["mean"])
            t1_ok &= bool(v.mean() <= 1.05 * ref)
            t1_rows.append(f"{s_} {mean_range(v)} vs {ref:.3f}")
        refsets = [("bench_v0 baselines (original W2)", False, False)]
        if rv:
            refsets += [("+ severity-free ridges", True, False), ("+ true-severity ridges (oracle reference)", True, True)]
        verdicts = []
        for label, add_nosev, add_true in refsets:
            rows, ok = [], True
            for s_ in W2_SPLITS:
                cand = {k: float(np.nanmean(v)) for k, v in bench["T2"]["168"][s_].items()}
                if add_nosev:
                    cand.update({k: v["mean"] for k, v in rv["T2"]["168"][s_].items() if "nosev" in k})
                if add_true:
                    cand.update({k: v["mean"] for k, v in rv["T2"]["168"][s_].items() if "truesev" in k})
                name = min(cand, key=cand.get)
                ref = cand[name]
                v = seeds(main_runs, lambda m: m["T2"]["168"][s_]["mean"])
                ok &= bool(v.mean() <= 0.9 * ref)
                rows.append(f"{s_} {mean_range(v)} vs {ref:.3f} {name} (≤ {0.9 * ref:.4f})")
            verdicts.append((label, ok, rows))
        # The headline is judged against the non-oracle set (bench + severity-free ridges); the true-severity ridges read the
        # future winter draw and are shown for information only.
        main_label, main_ok, _ = verdicts[1] if len(verdicts) > 1 else verdicts[0]
        txt = " ‖ ".join(f"[{lab}] " + "; ".join(r) + f" → {'pass' if okk else 'fail'}" for lab, okk, r in verdicts)
        W.append(("W2", "M1 main T2 168 h ≥ 10 % below the best baseline on A test, B test, OOD_long; T1 within +5 % "
                  "(judged against the best non-oracle baseline, the severity-free ridges included; the original bench-only verdict and the oracle reference beside it)",
                  "see Model column", txt + " — T1: " + "; ".join(t1_rows),
                  ("PASS" if main_ok and t1_ok else f"FAIL (T2 168 h {'pass' if main_ok else 'fail'}, T1 {'pass' if t1_ok else 'fail'})")
                  + f"; original: {'pass' if verdicts[0][1] else 'fail'} on T2 168 h"))
        tf = load("m1tf_main_r3_s0", "metrics.json")
        if tf:
            rows, ok = [], True
            for s_ in W2_SPLITS:
                cand = {k: float(np.nanmean(v)) for k, v in bench["T2"]["168"][s_].items()}
                if rv:
                    cand.update({k: v["mean"] for k, v in rv["T2"]["168"][s_].items() if "nosev" in k})
                name = min(cand, key=cand.get)
                ok &= bool(tf["T2"]["168"][s_]["mean"] <= 0.9 * cand[name])
                rows.append(f"{s_} {tf['T2']['168'][s_]['mean']:.3f} vs {cand[name]:.3f} {name}")
            t1ok = all(tf["T1"][s_]["mean"] <= 1.05 * min([float(np.nanmean(v)) for v in bench["T1"][s_].values()]
                                                          + ([v["mean"] for v in rv["T1"][s_].values()] if rv else []))
                       for s_ in TESTS)
            W.append(("W2b", "supplementary: the W2 test applied to M1b (transformer, recipe r3, one seed) — W2 itself is defined on M1",
                      "best non-oracle baseline", "T2 168 h: " + "; ".join(rows) + " — T1: " + "; ".join(f"{s_} {tf['T1'][s_]['mean']:.3f}" for s_ in TESTS),
                      "would PASS (one seed)" if ok and t1ok else "would FAIL"))
        # W3
        if "T4" in m0:
            parts, okc = [], True
            for target in ("dark_nights", "cold_member_hours"):
                wins, signs, detail = 0, [], []
                for variant in m0["T4"]["scores"]:
                    mv = seeds(main_runs, lambda m: m["T4"]["scores"][variant][target]["nmae"])
                    bv, bn = t4_best_baseline(base, variant, target)
                    sg = seeds(main_runs, lambda m: m["T4"]["scores"][variant][target]["sign_accuracy"])
                    wins += int(bv is not None and mv.mean() < bv)
                    signs.append(sg.mean())
                    detail.append(f"{variant} {mv.mean():.2f}/{fmt(bv, 2)} sign {sg.mean():.2f}")
                okt = wins >= 3 and float(np.mean(signs)) >= 0.75
                okc &= okt
                parts.append(f"{target}: below best baseline in {wins}/4, mean sign acc {np.mean(signs):.2f} ({'; '.join(detail)})")
            W.append(("W3", "T4 nMAE below the best baseline in ≥ 3 of 4 variants on dark nights and cold member-hours; sign ≥ 0.75",
                      "zero / val-mean effect", " | ".join(parts), "PASS" if okc else "FAIL"))
        # W4
        mv = seeds(main_runs, lambda m: m["T3b"]["A_test"]["mae"])
        ridge = base["T3b"]["A_test"]["ridge"]["mae"]
        oracle = base["T3b"]["A_test"]["severity_oracle"]["mae"]
        W.append(("W4", "T3b A test: M1 main MAE below the ridge; gap to the severity oracle", f"ridge {ridge:.3f}, oracle {oracle:.3f}",
                  f"M1 main {mean_range(mv)} (gap to oracle {mv.mean() - oracle:+.3f})", "PASS" if mv.mean() < ridge else "FAIL"))
    on = load(VARIANT_RUNS["sev-on, action-aware"], "metrics.json")
    if m0 and on:
        def winter(m, h):
            d = m["T2_any"][str(h)]["A_test"]["by_target_season"].get("3")
            return d["mean"] if d else float("nan")
        blind24 = seeds(main_runs, lambda m: winter(m, 24))
        blind168 = seeds(main_runs, lambda m: winter(m, 168))
        b3 = seeds(main_runs, lambda m: m["T3b"]["A_test"]["mae"])
        txt = (f"T2-any winter targets A test 24 h: blind {mean_range(blind24)} vs on {winter(on, 24):.3f}; 168 h: blind "
               f"{mean_range(blind168)} vs on {winter(on, 168):.3f}; T3b MAE blind {mean_range(b3)} vs on {on['T3b']['A_test']['mae']:.3f}")
        if "T4" in on:
            dn = lambda m: np.mean([m["T4"]["scores"][v]["dark_nights"]["nmae"] for v in m["T4"]["scores"]])
            txt += f"; T4 dark-night nMAE (mean of variants) blind {mean_range(seeds(main_runs, dn))} vs on {dn(on):.3f}"
        W.append(("W5", "severity ablation (T2 winter rows, T3b, T4) with the three-seed spread", "—", txt,
                  "REPORTED" if len(main_runs) == 3 else f"PARTIAL ({len(main_runs)} seed(s))"))
    m2 = None
    for r in ("m2_mlp_s0", "m2_set_s0", "m2_s0"):
        if load(r, "metrics.json") and load(r, "config.json") and load(r, "config.json").get("selected", True):
            m2 = (r, load(r, "metrics.json"))
            break
    if m2:
        a = m2[1]["A_test"]
        ok = (a["m2"]["state_tag_accuracy"] >= a["persistence"]["state_tag_accuracy"] + 0.05
              and a["m2"]["position_chebyshev"] < a["persistence"]["position_chebyshev"])
        W.append(("W6", "M2 T5 A test: state-tag acc ≥ persistence + 5 points; position error below persistence",
                  f"persistence acc {a['persistence']['state_tag_accuracy']:.3f}, Chebyshev {a['persistence']['position_chebyshev']:.3f}",
                  f"M2 ({m2[0]}) acc {a['m2']['state_tag_accuracy']:.3f}, Chebyshev {a['m2']['position_chebyshev']:.3f}",
                  "PASS" if ok else "FAIL"))
    rr = load(MAIN_SEEDS[0] + "_rerun", "metrics.json")
    if m0 and rr:
        diffs, missing = [], []

        def walk(x, y, path=""):
            if isinstance(x, dict):
                for k in x:
                    if k in ("config", "eval_code_commit", "seconds", "argv", "forced"):
                        continue
                    if not isinstance(y, dict) or k not in y:
                        missing.append(path + "/" + k)
                        continue
                    walk(x[k], y[k], path + "/" + k)
            elif isinstance(x, list):
                if not isinstance(y, list) or len(x) != len(y):
                    missing.append(path)
                    return
                for i, (p_, q_) in enumerate(zip(x, y)):
                    walk(p_, q_, f"{path}[{i}]")
            elif isinstance(x, (int, float)) and not isinstance(x, bool):
                if not isinstance(y, (int, float)):
                    missing.append(path)
                elif not (np.isnan(x) and np.isnan(y)):
                    diffs.append(abs(x - y))
        walk(m0, rr)
        mx = max(diffs) if diffs else float("nan")
        W.append(("W7", "same-seed rerun reproduces test metrics to 1e-6 (or nondeterminism measured)", "—",
                  f"max |diff| over {len(diffs)} test numbers (T4 effects included; {len(missing)} missing keys): {mx:.2e}",
                  "PASS" if mx <= 1e-6 and not missing else "MEASURED (see DECISIONS)"))
    rev = DOCS / "REVIEW.md"
    confirmed = rev.exists() and "W8 (leakage audit): CONFIRMED" in rev.read_text()
    W.append(("W8", "leakage audit by an independent reviewer", "—",
              "independent general-purpose reviewer, REVIEW.md" if rev.exists() else "pending",
              "CONFIRMED" if confirmed else ("see REVIEW.md" if rev.exists() else "PENDING")))
    L += ["## W table", "", "| # | Target | Baseline | Model | Result |", "|---|---|---|---|---|"]
    L += [f"| {a} | {b_} | {c_} | {d_} | {e} |" for a, b_, c_, d_, e in W]
    L.append("")
    # ---------------------------------------------------------------- model tables
    models = [(n, r) for n, r in VARIANT_RUNS.items() if load(r, "metrics.json")]
    other = [r for r in RECIPES if r != recipe]
    extra = [("**M1b transformer (main, r3, 1 seed)**", "m1tf_main_r3_s0")]
    for o in other:
        om, ov = runs_for(RECIPES[o])
        extra += [(f"{n} [{o}]", r) for n, r in ov.items()] + [(f"M1 main s{i} [{o}]", om[i]) for i in (1, 2)]
    models += [(n, r) for n, r in extra if load(r, "metrics.json")]
    for task, hs in (("T1", (None,)), ("T2", ("24", "168")), ("T2_any", ("24", "168"))):
        for h in hs:
            title = {"T1": "T1 next hour", "T2": f"T2 {h} h (bench starts, 06:00)", "T2_any": f"T2-any {h} h (every hour of the start days)"}[task]
            L += [f"## {title}", "", "| Predictor | " + " | ".join(TESTS) + " |", "|---|" + "---:|" * len(TESTS)]
            bsrc = base[task] if h is None else base[task][h]
            for name in ("persistence", "daily_naive", "ridge", "ridge_action"):
                L.append(f"| {name} | " + " | ".join(fmt(bsrc[s][name]["mean"]) for s in TESTS) + " |")
            if rv:
                rsrc = rv[task] if h is None else rv[task][h]
                for name in rsrc[TESTS[0]]:
                    lab = name + (" (oracle reference)" if "truesev" in name else "")
                    L.append(f"| {lab} | " + " | ".join(fmt(rsrc[s][name]["mean"]) for s in TESTS) + " |")
            if main_runs:
                L.append("| **M1 main (3 seeds)** | " + " | ".join(mean_range(seeds(main_runs, lambda m: (m[task] if h is None else m[task][h])[s]["mean"])) for s in TESTS) + " |")
            for name, r in models[1:]:
                m = load(r, "metrics.json")
                src = m[task] if h is None else m[task][h]
                L.append(f"| {name} | " + " | ".join(fmt(src[s]["mean"]) if s in src and src[s] else "—" for s in TESTS) + " |")
            L.append("")
    if m0:
        L += ["## Per variable — M1 main seed 0 vs the best baseline (A test)", "",
              "| Task | Predictor | " + " | ".join(b.VARS) + " | mean |", "|---|---|" + "---:|" * (len(b.VARS) + 1)]
        for task, h in (("T1", None), ("T2", "24"), ("T2", "168")):
            bsrc = base[task] if h is None else base[task][h]
            msrc = m0[task] if h is None else m0[task][h]
            _, bn = best_baseline(bsrc["A_test"])
            lab = task + ("" if h is None else f" {h} h")
            for name, src in ((bn, bsrc["A_test"][bn]), ("M1 main s0", msrc["A_test"])):
                L.append(f"| {lab} | {name} | " + " | ".join(fmt(x) for x in src["per_var"]) + f" | {fmt(src['mean'])} |")
        L.append("")
        L += ["## T2 by target season (A test, M1 main s0 vs action ridge, any-hour starts)", "",
              "| Horizon | Season | n | ridge_action | M1 main s0 |", "|---|---|---:|---:|---:|"]
        for h in ("24", "168"):
            bs = base["T2_any"][h]["A_test"]["ridge_action"]["by_target_season"]
            ms = m0["T2_any"][h]["A_test"]["by_target_season"]
            for k in sorted(ms, key=int):
                L.append(f"| {h} h | {k} | {ms[k]['n']} | {fmt(bs.get(k, {}).get('mean'))} | {fmt(ms[k]['mean'])} |")
        L.append("")
    # T3 / T3b
    L += ["## T3 dark night (A test)", "", "| Predictor | Brier | AUC | Accuracy |", "|---|---:|---:|---:|"]
    for n in ("rule", "logistic"):
        s = base["T3"][n]
        L.append(f"| {n} | {fmt(s['brier'], 4)} | {fmt(s['auc'])} | {fmt(s['accuracy'])} |")
    for name, r in ([("M1 main s" + r[-1], r) for r in main_runs] + models[1:]):
        m = load(r, "metrics.json")
        if m and "T3" in m:
            L.append(f"| {name} | {fmt(m['T3']['brier'], 4)} | {fmt(m['T3']['auc'])} | {fmt(m['T3']['accuracy'])} |")
    L += ["", "## T3b winter outlook", "", "| Predictor | " + " | ".join(f"{s} MAE / exact" for s in TESTS) + " |",
          "|---|" + "---:|" * len(TESTS)]
    for n in ("train_mean", "ridge", "severity_oracle"):
        L.append(f"| {n} | " + " | ".join(
            f"{fmt(base['T3b'][s][n]['mae'])} / {fmt(base['T3b'][s][n]['exact_accuracy'], 2)}" if n in base["T3b"].get(s, {}) else "—"
            for s in TESTS) + " |")
    for n in ("ridge", "ridge_action"):
        L.append(f"| {n} rollout | " + " | ".join(
            f"{fmt(base['T3b_rollout'][s][n]['mae'])} / {fmt(base['T3b_rollout'][s][n]['exact_accuracy'], 2)}" for s in TESTS) + " |")
    for name, r in ([("M1 main s" + r[-1], r) for r in main_runs] + models[1:]):
        m = load(r, "metrics.json")
        if m:
            L.append(f"| {name} | " + " | ".join(
                f"{fmt(m['T3b'][s]['mae'])} / {fmt(m['T3b'][s]['exact_accuracy'], 2)}" if m["T3b"].get(s) else "—" for s in TESTS) + " |")
    L.append("")
    # T4
    if m0 and "T4" in m0:
        L += ["## T4 counterfactual (C_cf test): MAE / sign accuracy / normalized MAE", ""]
        preds = [("zero_effect", None), ("val_mean_effect", None)] + [("M1 main (3 seeds)", main_runs)] + \
                [(n, [r]) for n, r in models[1:] if "T4" in load(r, "metrics.json")]
        for variant in m0["T4"]["scores"]:
            L += [f"### {variant}", "", "| Predictor | " + " | ".join(b.T4_TARGETS) + " |", "|---|" + "---|" * len(b.T4_TARGETS)]
            for name, runs in preds:
                cells = []
                for t in b.T4_TARGETS:
                    if runs is None:
                        s = base["T4"][name][variant][t]
                        cells.append(f"{fmt(s['mae'])} / {fmt(s['sign_accuracy'], 2)} / {fmt(s['nmae'])}")
                    else:
                        mae = seeds(runs, lambda m: m["T4"]["scores"][variant][t]["mae"])
                        sg = seeds(runs, lambda m: m["T4"]["scores"][variant][t]["sign_accuracy"])
                        nm = [load(r, "metrics.json")["T4"]["scores"][variant][t]["nmae"] for r in runs]
                        nm = np.array([x for x in nm if x is not None], dtype=float)
                        cells.append(f"{mean_range(mae)} / {mean_range(sg, 2)} / {mean_range(nm) if len(nm) else '—'}")
                L.append(f"| {name} | " + " | ".join(cells) + " |")
            L.append("")
    # T5 / M2
    m2m = load("m2_set_s0", "metrics.json")
    if m2m:
        L += ["## T5 agent next hour (M2 = set transformer `m2_set_s0`)", "",
              "| Split | Predictor | State tag acc | Target kind acc | Chebyshev | Exact position | Needs nMAE (h / t / f) |",
              "|---|---|---:|---:|---:|---:|---|"]
        for sp in ("A_test", "B_test"):
            for name in ("persistence", "day_earlier", "m2"):
                x = m2m[sp][name]
                nn_ = " / ".join(fmt(x["needs_nmae"][k]) for k in ("hunger", "thirst", "fatigue"))
                L.append(f"| {sp} | {name} | {fmt(x['state_tag_accuracy'])} | {fmt(x['target_kind_accuracy'])} | "
                         f"{fmt(x['position_chebyshev'])} | {fmt(x['position_exact'])} | {nn_} |")
            ag = m2m[sp]["aggregate_adults_working"]
            L.append(f"| {sp} | aggregate `adults_working` nMAE | M2 {fmt(ag['model_nmae'])} | persistence {fmt(ag['persistence_nmae'])} | "
                     f"true-agent count {fmt(ag['true_agents_proxy_nmae'])} | | |")
        L.append("")
    m3m = load("m3_s0", "metrics.json")
    if m3m:
        c3 = load("m3_s0", "config.json")
        L += ["## M3 text world model (A test, T2 bench starts at day granularity)", "",
              f"LoRA r16 on `{c3['base'].split('models--')[-1].split('/')[0]}`; {c3.get('steps_done')} of {c3['steps_per_epoch']} "
              f"steps ({100 * c3.get('epoch_fraction', 0):.0f} % of one epoch) before the 2-hour cap.", "",
              "| Predictor | JSON parse rate | mean nMAE (24 h) | " + " | ".join(b.VARS) + " |", "|---|---:|---:|" + "---:|" * len(b.VARS),
              f"| daily naive | — | {fmt(m3m['daily_naive']['mean'])} | " + " | ".join(fmt(x) for x in m3m["daily_naive"]["per_var"]) + " |",
              f"| M3 | {fmt(m3m['parse_rate'])} | {fmt(m3m['m3']['mean'])} | " + " | ".join(fmt(x) for x in m3m["m3"]["per_var"]) + " |", ""]
    # training / validation summary
    L += ["## Runs (validation)", "", "| Run | Model | Variant | Seed | Device | Best val T2 24 h | Best step | Stop | Round counts | Calibration (±2σ) | Train s |",
          "|---|---|---|---:|---|---:|---:|---|---|---:|---:|"]
    for p in sorted(RUNS.iterdir()):
        cfg, val = load(p.name, "config.json"), load(p.name, "val_metrics.json")
        if not cfg or not val or "variant" not in cfg:
            continue
        cal = val.get("calibration_val", {}).get("within_2sigma_mean")
        L.append(f"| {p.name} | {cfg['model']} | {cfg['variant']} | {cfg['seed']} | {cfg['device']} | {fmt(val['best_val_t2_24'], 4)} | "
                 f"{val['best_step']} | {val['stop']} | {val['round_counts']} | {fmt(cal)} | {val['seconds']:.0f} |")
    L.append("")
    (DOCS / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(f"{a}: {e}" for a, _, _, _, e in W))
    return 0


