def metrics_runs() -> str:
    """The generated "Runs" section of METRICS.md: every trained run with its configuration, val and test numbers,
    DGX directory, checkpoint and the command that retrains it."""
    from wm1 import m1_gru
    dgx = "/home/hyunlord/work/wm1-runs"
    L = ["## Runs (generated by `tools/worldmodel/wm1/report.py --metrics`)", "",
         "Val = mean of A val and B val (M2: A val); test columns are A test unless named. DGX run directory = "
         f"`{dgx}/<run>/` (checkpoint `best.pt`; M3: `lora/`). Retrain from a clone at the run's code commit "
         "(`code_commit.txt`) with `WM_DATA_ROOT=/home/hyunlord/work/worldsim-wm-data` and the venv's python; "
         "evaluate with `m1_gru.py final --run <dir>` (M2: `m2_agents.py final`, M3: `m3_text.py final`).", "",
         "| Run | Model / variant / seed | Device | Steps (best) | Val T1 | Val T2-24 | Val T2-168 | Test T1 | Test T2-24 | Test T2-168 (A / B / OOD_long) | Test T3b | Code |",
         "|---|---|---|---|---:|---:|---:|---:|---:|---|---:|---|"]
    cmds = []
    for p in sorted(RUNS.iterdir()):
        cfg, val, met = load(p.name, "config.json"), load(p.name, "val_metrics.json"), load(p.name, "metrics.json")
        if not cfg or cfg.get("model") not in ("m1_gru", "m1_tf"):
            continue
        vm = lambda t, h=None: float(np.mean([(val["val"][t] if h is None else val["val"][t][h])[n]["mean"] for n in ("A_val", "B_val")]))
        test = lambda t, s, h=None: (met[t] if h is None else met[t][h])[s]["mean"]
        tcol = (f"{fmt(test('T1', 'A_test'))} | {fmt(test('T2', 'A_test', '24'))} | "
                f"{fmt(test('T2', 'A_test', '168'))} / {fmt(test('T2', 'B_test', '168'))} / {fmt(test('T2', 'OOD_long', '168'))} | "
                f"{fmt(met['T3b']['A_test']['mae'])}") if met else "— | — | — | —"
        code = (RUNS / p.name / "code_commit.txt").read_text().strip()[:8] if (RUNS / p.name / "code_commit.txt").exists() else "—"
        L.append(f"| `{p.name}` | {cfg['model']} / {cfg['variant']} / {cfg['seed']} | {cfg['device']} | {val['last_step']} ({val['best_step']}) | "
                 f"{fmt(vm('T1'))} | {fmt(vm('T2', '24'))} | {fmt(vm('T2', '168'))} | {tcol} | `{code}` |")
        defaults = m1_gru.DEFAULTS if cfg["model"] == "m1_gru" else __import__("wm1.m1_tf", fromlist=["DEFAULTS"]).DEFAULTS
        flags = " ".join(f"--{k.replace('_', '-')} {v}" for k, v in cfg["hyper"].items() if defaults.get(k) != v)
        script = "m1_gru.py train" if cfg["model"] == "m1_gru" else "m1_tf.py train"
        cmds.append(f"{p.name}: python tools/worldmodel/wm1/{script} --out {dgx}/{p.name} --variant {cfg['variant']} --seed {cfg['seed']} {flags}")
    for name in ("m2_mlp_s0", "m2_set_s0"):
        cfg, val, met = load(name, "config.json"), load(name, "val_metrics.json"), load(name, "metrics.json")
        if cfg:
            L.append(f"| `{name}` | m2 ({cfg['arch']}) / — / {cfg['seed']} | {cfg['device']} | {val['steps']} | val state-tag {fmt(val['val']['state_tag_accuracy'])} | "
                     f"val Chebyshev {fmt(val['val']['position_chebyshev'])} | val score {fmt(val['val_score'])} | "
                     + (f"state-tag {fmt(met['A_test']['m2']['state_tag_accuracy'])} | Chebyshev {fmt(met['A_test']['m2']['position_chebyshev'])} | "
                        f"needs nMAE {fmt(met['A_test']['m2']['needs_nmae_mean'])} | — |" if met else "not test-evaluated (not selected) | | | |")
                     + f" `{(RUNS / name / 'code_commit.txt').read_text().strip()[:8]}` |")
            cmds.append(f"{name}: python tools/worldmodel/wm1/m2_agents.py train --out {dgx}/{name} --arch {cfg['arch']} --seed {cfg['seed']} "
                        + " ".join(f"--{k.replace('_', '-')} {v}" for k, v in cfg["hyper"].items() if k in ("epochs", "threads") ))
    cfg, met = load("m3_s0", "config.json"), load("m3_s0", "metrics.json")
    if cfg:
        L.append(f"| `m3_s0` | m3 (LoRA r{cfg['hyper']['rank']}, Qwen2.5-0.5B-Instruct) / — / {cfg['seed']} | cpu | {cfg.get('steps_done')} of {cfg['steps_per_epoch']} | — | — | — | "
                 + (f"parse rate {fmt(met['parse_rate'])} | 24 h nMAE {fmt(met['m3']['mean'])} (daily naive {fmt(met['daily_naive']['mean'])}) | — | — |" if met else "pending | | | |")
                 + f" `{(RUNS / 'm3_s0' / 'code_commit.txt').read_text().strip()[:8]}` |")
        cmds.append(f"m3_s0: python tools/worldmodel/wm1/m3_text.py train --out {dgx}/m3_s0 --threads {cfg['hyper']['threads']}")
    L += ["", "### Retrain commands", "", "```"] + cmds + ["```", ""]
    return "\n".join(L)


