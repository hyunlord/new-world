"""Validate complete M6a gate execution and generated output inventories."""
from __future__ import annotations

import re
from pathlib import Path
from typing import Final

import core_shadow_freeze as freeze
from m6a_evidence import Node, Reference, reference_json, write_json
from m6a_gate_source import Gate, keys, need, ref
from m6a_gate_art import validate as validate_plant_art

STEP_PATTERN: Final = re.compile(r'^\s*(\d+)\s+(\w+)\s+exit\s+(\d+)\s+\d+s\s+started\s+\S+\s*$', re.MULTILINE)


def gate_steps(text: str, head: str) -> tuple[tuple[int, str, int], ...]:
    need(text.startswith('head ' + head + '\n'), 'gate HEAD mismatch')
    need(re.findall(r'^dirty (\d+)$', text, re.MULTILINE) == ['0'], 'gate tree was dirty')
    rows = tuple((int(number), name, int(code)) for number, name, code in STEP_PATTERN.findall(text))
    need(len(rows) == 48 and {number for number, _, _ in rows} == set(range(1, 49)),
         'gate requires 48 unique executed steps')
    need(all(code == 0 or (number, name) in ((12, 'perf'), (27, 'nav_bench'))
             for number, name, code in rows), 'mandatory gate step failed (no M6a waiver)')
    need(len(re.findall(r'^finished .* status 0$', text, re.MULTILINE)) == 1
         and text.rstrip().endswith('status 0'), 'missing successful terminal record')
    return rows


def seal(gate: Gate, output: Path) -> None:
    """Bind all generated bytes after subprocess completion, refusing output reuse."""
    gate.verify()
    files = sorted(path for path in output.rglob('*') if path.is_file())
    need(bool(files), 'empty step output')
    write_json(output / 'gate-receipt.json', {'schema_version': 1,
        'config_sha256': gate.checksum, 'head': gate.head,
        'files': [reference_json(path) for path in files]})


def receipt(gate: Gate, directory: str) -> Path:
    path = gate.output / directory / 'gate-receipt.json'
    data = Node.load(path)
    keys(data, {'schema_version', 'config_sha256', 'head', 'files'})
    need(data.get('schema_version').integer() == 1 and data.get('config_sha256').text() == gate.checksum
         and data.get('head').text() == gate.head, 'step receipt belongs to another gate')
    paths = [ref(gate.root, row) for row in data.get('files').rows()]
    need(len(paths) == len(set(paths)) and bool(paths), 'duplicate/empty step inventory')
    actual = {item for item in path.parent.rglob('*') if item.is_file() and item != path}
    need(set(paths) == actual, 'step output inventory incomplete')
    return path


def final(gate: Gate) -> None:
    gate.verify()
    summary = gate.output / 'gate.txt'
    rows = gate_steps(summary.read_text(), gate.head)
    need(all(code == 0 for number, _, code in rows if number in (12, 27)),
         'report-only timing process did not finish; invalid measurements are not results')
    script = (gate.root / 'tools/v8/gate.sh').read_text()
    for number, name, _ in rows:
        need(re.search(rf'^\s*step {number} {re.escape(name)} ', script, re.MULTILINE) is not None,
             'gate step name differs from committed command')
        log = gate.output / (name + '.log')
        need(log.is_file() and log.stat().st_size > 0, 'missing execution log')
    for filename in ('nav-bench-admission.jsonl', 'perf/admission.jsonl'):
        admission = gate.output / filename
        records = [Node.parse(line) for line in admission.read_text().splitlines()]
        admitted = [row for row in records if row.get('status').text() == 'ADMITTED']
        need(bool(admitted), 'no admitted timing repetition')
        for row in admitted:
            loads = row.get('loads_1_5_15').rows()
            need(len(loads) == 3, 'missing load triplet')
            value = loads[0].value
            need(type(value) in (int, float) and 0 <= value < 8, 'invalid timing admission')
    references = [reference_json(receipt(gate, name)) for name in
        ('core-shadow-fixture', 'core-evaluation', 'm6a-food-fixture', 'm6a-food-data-only')]
    art = Node.load(gate.output / 'm6a-food-data-only/plant-art-structural.json')
    need(art.get('kind').text() == 'm6a_plant_art_structural_v1'
         and art.get('head').text() == gate.head and art.get('exit_code').integer() == 0
         and art.get('status').text() == 'PASS'
         and art.get('visual_status').text() == 'NOT_EVALUATED',
         'step48 plant art structural receipt absent or invalid')
    need(validate_plant_art(ref(gate.root, art.get('log')).read_text()) == art.get('checks').integer(),
         'step48 plant art structural receipt differs from process output')
    write_json(gate.output / 'm6a-final.json', {'schema_version': 1, 'head': gate.head,
        'config': reference_json(gate.path), 'gate': reference_json(summary),
        'step_receipts': references, 'status': 'PASS', 'waivers': []})


def calibration(gate: Gate) -> None:
    """Audit every started round, retaining failed attempts within the four-round cap."""
    binding = gate.data.get('calibration')
    keys(binding, {'register', 'freeze'})
    register = ref(gate.root, binding.get('register'))
    frozen_path = ref(gate.root, binding.get('freeze'))
    frozen = Node.load(frozen_path)
    need(frozen.get('schema_version').integer() == 1 and frozen.get('kind').text() == 'm6a_freeze_v1',
         'wrong calibration freeze protocol')
    need(ref(gate.root, frozen.get('calibration_register')) == register, 'register differs from freeze')
    need(frozen.get('source_hash').text() == gate.frozen_source_hash()
         and frozen.get('binary_sha256').text() == freeze.digest(gate.binary())
         and frozen.get('scorer_sha256').text() == freeze.digest(gate.root / 'tools/v8/m6a_score.py'),
         'candidate/instrument changed after freeze')
    need(frozen.get('days').integer() == 72
         and [row.integer() for row in frozen.get('heldout_seeds').rows()] == list(range(1296, 1328)),
         'freeze changes heldout protocol')
    events = [Node.parse(line) for line in register.read_text().splitlines()]
    need(bool(events) and len(events) <= 8 and len(events) % 2 == 0, 'invalid calibration round count')
    for offset in range(0, len(events), 2):
        start, end = events[offset:offset + 2]
        number = offset // 2 + 1
        need(start.get('event').text() == 'started' and end.get('event').text() == 'finished'
             and start.get('round').integer() == end.get('round').integer() == number,
             'duplicate/hidden/unfinished calibration round')
        need([row.integer() for row in start.get('seeds').rows()] == list(range(8)), 'wrong calibration seeds')
        path = ref(gate.root, end.get('receipt'))
        round_data = Node.load(path)
        need(path.parent == Path(start.get('out').text())
             and round_data.get('round').integer() == number
             and round_data.get('purpose').text() == 'calibration'
             and round_data.get('days').integer() == 72
             and [row.integer() for row in round_data.get('seeds').rows()] == list(range(8)),
             'calibration receipt mismatch')
        need(round_data.get('exit_code').integer() == end.get('exit_code').integer(), 'round exit mismatch')
        if offset == len(events) - 2:
            need(round_data.get('exit_code').integer() == 0
                 and round_data.get('source_hash').text() == frozen.get('source_hash').text(),
                 'final calibration did not finish on frozen source')
    heldout = gate.data.get('heldout')
    keys(heldout, {'candidate', 'base'})
    for arm in ('candidate', 'base'):
        row = Node.load(ref(gate.root, heldout.get(arm)))
        need(row.get('purpose').text() == 'heldout' and row.get('arm').text() == arm
             and row.get('exit_code').integer() == 0 and row.get('source_unchanged').boolean(),
             'incomplete heldout process')
        need(ref(gate.root, row.get('freeze')) == frozen_path, 'heldout did not use this freeze')
        if arm == 'base' and gate.observer_successor():
            from m6a_base72 import validate_cohort
            validate_cohort(gate.root, ref(gate.root, gate.data.get('base_observer')),
                            ref(gate.root, heldout.get('base')))
        else:
            need(ref(gate.root, row.get('binary')) == gate.binary(arm + '_build'),
                 'stale/swapped heldout binary')
        if arm == 'candidate':
            need(row.get('source_hash').text() == frozen.get('source_hash').text(), 'heldout source changed')
