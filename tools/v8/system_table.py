#!/usr/bin/env python3
"""Generate the live system table of docs/ARCHITECTURE.md (goal 9.5).

The registration code is the source of truth: `worldsim_systems` (a sim-test
binary) builds the live engine (`build_game_engine`'s colony world) and
prints one JSON object per registered system in execution order
(`name`, `priority`, `interval`). Each name is mapped to its file by the
`fn name(&self) -> &str { "<Name>" }` literal under
`rust/crates/sim-systems/src`, and the `Reads:` / `Writes:` lines of that
file's `//!` header fill the last two columns.

usage: system_table.py [--json SYSTEMS.jsonl] --print   print the table
       system_table.py [--json SYSTEMS.jsonl] --write   rewrite the table in docs/ARCHITECTURE.md
       system_table.py [--json SYSTEMS.jsonl] --check   exit 1 if docs/ARCHITECTURE.md differs
Without --json the binary is run with `cargo run --release -q -p sim-test --bin worldsim_systems`.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs/ARCHITECTURE.md"
BEGIN = "<!-- system-table:begin (generated by tools/v8/system_table.py; do not edit) -->"
END = "<!-- system-table:end -->"
NAME_RE = re.compile(r'fn name\(&self\) -> &str \{\s*"([A-Za-z]+)"')


def registered(json_path=None):
    if json_path:
        text = Path(json_path).read_text()
    else:
        text = subprocess.run(["cargo", "run", "--release", "-q", "-p", "sim-test", "--bin", "worldsim_systems"],
                              cwd=ROOT / "rust", capture_output=True, text=True, check=True).stdout
    return [json.loads(line) for line in text.splitlines() if line.strip()]


def system_files():
    files = {}
    for path in sorted((ROOT / "rust/crates/sim-systems/src").rglob("*.rs")):
        for name in NAME_RE.findall(path.read_text()):
            files[name] = path
    return files


def header_field(path, field):
    for line in path.read_text().splitlines():
        if not line.startswith("//!"):
            break
        m = re.match(rf"//!\s*{field}:\s*(.*)", line)
        if m:
            return m.group(1).strip()
    return "?"


def own_part(field, name):
    """A file holding several systems writes each field as `A — …; B — …`;
    return the part that belongs to `name` (the whole field otherwise)."""
    parts = re.split(r";\s*(?=[A-Z][A-Za-z]+System — )", field)
    for part in parts:
        if part.startswith(f"{name} — "):
            return part[len(name) + 3:].strip()
    return field


def table(json_path=None):
    files = system_files()
    lines = [BEGIN, "", "| # | system | priority | interval (ticks) | file | reads | writes |", "|---|---|---|---|---|---|---|"]
    for index, row in enumerate(registered(json_path), 1):
        path = files.get(row["name"])
        rel = path.relative_to(ROOT).as_posix() if path else "?"
        reads = own_part(header_field(path, "Reads"), row["name"]) if path else "?"
        writes = own_part(header_field(path, "Writes"), row["name"]) if path else "?"
        lines.append(f"| {index} | `{row['name']}` | {row['priority']} | {row['interval']} | `{rel}` | {reads} | {writes} |")
    lines += ["", END]
    return "\n".join(lines)


def current_block():
    text = DOC.read_text()
    if BEGIN not in text or END not in text:
        return None, text
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    return text[start:end], text


def main(argv):
    json_path = argv[argv.index("--json") + 1] if "--json" in argv else None
    if "--print" in argv:
        print(table(json_path))
        return 0
    if "--write" in argv:
        block, text = current_block()
        if block is None:
            print("docs/ARCHITECTURE.md has no system-table markers", file=sys.stderr)
            return 1
        DOC.write_text(text.replace(block, table(json_path)))
        print("system table written")
        return 0
    if "--check" in argv:
        block, _ = current_block()
        fresh = table(json_path)
        if block != fresh:
            print("system table: FAIL (docs/ARCHITECTURE.md differs from tools/v8/system_table.py output)")
            return 1
        print("system table: PASS")
        return 0
    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
