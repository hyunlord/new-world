/// E(u) = −ln(1 − u / 10⁶) in thousandths for `u` in `0..10⁶`, linearly
/// interpolated between the entries of [`EXP_TABLE`] (integers only).
pub const fn exp_quantile_permille(u: u64) -> u64 {
    let u = if u >= THRESHOLD_DRAW_RESOLUTION { THRESHOLD_DRAW_RESOLUTION - 1 } else { u };
    let x = u * 1024;
    let i = (x / THRESHOLD_DRAW_RESOLUTION) as usize;
    let frac = x % THRESHOLD_DRAW_RESOLUTION;
    let lo = EXP_TABLE[i] as u64;
    let hi = EXP_TABLE[i + 1] as u64;
    lo + (hi - lo) * frac / THRESHOLD_DRAW_RESOLUTION
}

/// The uniform value behind the threshold of settlement `sid` after `k` splits.
pub const fn threshold_draw(world_seed: u64, sid: u64, k: u32) -> u64 {
    keyed_below(world_seed, STREAM_FISSION_THRESHOLD, sid, 0, k, 0, THRESHOLD_DRAW_RESOLUTION)
}

/// θ for a uniform value `u` in `0..10⁶` under `law` (thousandths, at least 1).
pub const fn threshold_from_draw(law: ThresholdLaw, u: u64) -> u64 {
    let theta = match law {
        ThresholdLaw::Exponential { mean_permille } => mean_permille as u64 * exp_quantile_permille(u) / 1000,
        ThresholdLaw::Uniform { lo_permille, hi_permille } => {
            let (lo, hi) = (lo_permille as u64, hi_permille as u64);
            let span = hi.saturating_sub(lo);
            lo + span * u / THRESHOLD_DRAW_RESOLUTION
        }
    };
    if theta == 0 {
        1
    } else {
        theta
    }
}

/// θ of settlement `sid` in world `world_seed` after `k` splits under `law`.
pub const fn fission_threshold(law: ThresholdLaw, world_seed: u64, sid: u64, k: u32) -> u64 {
    threshold_from_draw(law, threshold_draw(world_seed, sid, k))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_ends_and_interpolation() {
        assert_eq!((EXP_TABLE[0], EXP_TABLE[512], EXP_TABLE[1023], EXP_TABLE[1024]), (0, 693, 6931, 7625));
        assert!(EXP_TABLE.windows(2).all(|w| w[0] < w[1]));
        assert_eq!(exp_quantile_permille(0), 0);
        // u = 0.5: the entry at 512 exactly.
        assert_eq!(exp_quantile_permille(500_000), 693);
        // Halfway between entries 1 and 2 (1 and 2 thousandths).
        assert_eq!(exp_quantile_permille(1465), 1);
        // The top of the range stays below the cap.
        assert!(exp_quantile_permille(999_999) <= 7625);
    }

    #[test]
    fn laws() {
        assert_eq!(threshold_from_draw(ThresholdLaw::Exponential { mean_permille: 1200 }, 500_000), 1200 * 693 / 1000);
        assert_eq!(threshold_from_draw(ThresholdLaw::Exponential { mean_permille: 1200 }, 0), 1);
        assert_eq!(threshold_from_draw(ThresholdLaw::Uniform { lo_permille: 600, hi_permille: 1600 }, 250_000), 850);
        assert_eq!(threshold_from_draw(ThresholdLaw::Uniform { lo_permille: 0, hi_permille: 0 }, 250_000), 1);
    }
}
