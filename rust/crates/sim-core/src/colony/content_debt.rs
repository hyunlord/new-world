//! Deterministic generated ledger for authored content awaiting behavior wiring.
use super::content::Catalog;
use super::knowledge::ContentStatus;

fn cell(value: &str) -> String {
    value.replace('|', "\\|").replace(['\n', '\r'], " ")
}

fn row(out: &mut String, id: &str, kind: &str, era: &str, lane: &str, debt: Option<&str>) {
    let debt = debt.unwrap_or("Missing behavior wiring; future content pass");
    let planned = ["C1", "C2", "C3", "M-GROW", "M-NATION", "M-BAL", "M8"]
        .into_iter()
        .find(|name| debt.contains(name))
        .unwrap_or("후속 콘텐츠 패스");
    out.push_str(&format!(
        "| {} | {kind} | {} | {} | {} | {planned} |\n",
        cell(id),
        cell(era),
        cell(lane),
        cell(debt)
    ));
}

/// Render only the generated section; hand-authored historical debt is preserved by the writer.
pub fn render(catalog: &Catalog) -> String {
    let mut out = "<!-- generated-content-debt -->\n\n## Authored inert content\n\nGenerated by `cargo run -p sim-test --bin content_debt`.\n\n| id | kind | era | lane | what is missing | planned pass |\n| --- | --- | --- | --- | --- | --- |\n".to_owned();
    let defs = catalog.knowledge_defs();
    for node in &defs.nodes {
        if node.status == ContentStatus::Inert {
            let lane = defs
                .eras
                .lanes
                .get(usize::from(node.lane.code()))
                .map(|l| l.id.as_str())
                .unwrap_or("");
            let era = defs
                .eras
                .eras
                .get(usize::from(node.era.code()))
                .map(|e| e.id.as_str())
                .unwrap_or("");
            let mut debt = node.debt.clone().unwrap_or_default();
            if !node.inert_gates.is_empty() {
                debt.push_str("; ignored gates: ");
                debt.push_str(&node.inert_gates.join(", "));
            }
            row(&mut out, &node.name, "knowledge", era, lane, Some(&debt));
        }
    }
    for item in catalog.items() {
        if item.status == ContentStatus::Inert {
            row(
                &mut out,
                &item.identity.id,
                "item",
                &item.era,
                &item.lane,
                item.debt.as_deref(),
            );
        }
    }
    out
}
