//! Deterministic generated ledger for authored content awaiting behavior wiring.
use super::content::Catalog;
use super::knowledge::ContentStatus;

fn cell(value: &str) -> String {
    value.replace('|', "\\|").replace(['\n', '\r'], " ")
}

fn has_debt(status: ContentStatus, debt: Option<&str>) -> bool {
    status == ContentStatus::Inert || debt.is_some_and(|value| !value.trim().is_empty())
}

fn row(
    out: &mut String,
    id: &str,
    kind: &str,
    era: &str,
    lane: &str,
    status: ContentStatus,
    debt: Option<&str>,
) {
    let debt = debt.unwrap_or("Missing behavior wiring; future content pass");
    let planned = [
        "C1-b", "C1-a", "C1", "C2", "C3", "M-GROW", "M-NATION", "M-BAL", "M7", "M8", "M9",
    ]
    .into_iter()
    .find(|name| debt.contains(name))
    .unwrap_or("후속 콘텐츠 패스");
    let status = match status {
        ContentStatus::Connected => "Connected",
        ContentStatus::Inert => "Inert",
    };
    out.push_str(&format!(
        "| {} | {kind} | {} | {} | {status} | {} | {planned} |\n",
        cell(id),
        cell(era),
        cell(lane),
        cell(debt)
    ));
}

/// Render only the generated section; hand-authored historical debt is preserved by the writer.
pub fn render(catalog: &Catalog) -> String {
    let mut out = "<!-- generated-content-debt -->\n\n## Authored content debt\n\nGenerated by `cargo run -p sim-test --bin content_debt`. Connected rows retain a working effect while recording the missing effects.\n\n| id | kind | era | lane | status | what is missing | planned pass |\n| --- | --- | --- | --- | --- | --- | --- |\n".to_owned();
    let defs = catalog.knowledge_defs();
    for node in &defs.nodes {
        if has_debt(node.status, node.debt.as_deref()) {
            let lane = defs
                .eras
                .lanes
                .get(usize::from(node.lane.code()))
                .map(|l| l.id.as_str())
                .unwrap_or("");
            let era = defs
                .eras
                .eras
                .get(usize::from(node.era.code()))
                .map(|e| e.id.as_str())
                .unwrap_or("");
            let mut debt = node.debt.clone().unwrap_or_default();
            if !node.inert_gates.is_empty() {
                debt.push_str("; ignored gates: ");
                debt.push_str(&node.inert_gates.join(", "));
            }
            row(
                &mut out,
                &node.name,
                "knowledge",
                era,
                lane,
                node.status,
                Some(&debt),
            );
        }
    }
    for item in catalog.items() {
        if has_debt(item.status, item.debt.as_deref()) {
            row(
                &mut out,
                &item.identity.id,
                "item",
                &item.era,
                &item.lane,
                item.status,
                item.debt.as_deref(),
            );
        }
    }
    for animal in catalog.animals() {
        if has_debt(animal.status, animal.debt.as_deref()) {
            row(
                &mut out,
                &animal.identity.id,
                "animal",
                "",
                "animals",
                animal.status,
                animal.debt.as_deref(),
            );
        }
    }
    for template in &catalog.building_templates().buildings {
        if has_debt(template.status, template.debt.as_deref()) {
            row(
                &mut out,
                &template.id,
                "template",
                &template.era,
                "building",
                template.status,
                template.debt.as_deref(),
            );
        }
    }
    for zone in catalog.building_templates().zone_kinds() {
        if has_debt(zone.status, zone.debt.as_deref()) {
            row(
                &mut out,
                &zone.id,
                "zone",
                "",
                "building",
                zone.status,
                zone.debt.as_deref(),
            );
        }
    }
    out
}
